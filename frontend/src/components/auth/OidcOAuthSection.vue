<template>
  <div class="space-y-4">
    <button type="button" :disabled="disabled" class="btn btn-secondary btn-outline w-full" @click="startLogin">
      <span
        class="mr-2 inline-flex h-5 w-5 shrink-0 items-center justify-center text-xs font-semibold text-[var(--foreground)]"
      >
        {{ providerInitial }}
      </span>
      {{ t('auth.oidc.signIn', { providerName: normalizedProviderName }) }}
    </button>

    <div v-if="showDivider" class="flex items-center gap-3">
      <div class="h-px flex-1 bg-[var(--border)]"></div>
      <span class="text-xs text-[var(--muted-foreground)]">
        {{ t('auth.oauthOrContinue') }}
      </span>
      <div class="h-px flex-1 bg-[var(--border)]"></div>
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed } from 'vue'
import { useRoute } from 'vue-router'
import { useI18n } from 'vue-i18n'
import type { OAuthLoginStart } from '@/api/auth'
import { sanitizeInternalRedirect } from '@/router/redirect'
import { resolveAffiliateReferralCode, storeOAuthAffiliateCode } from '@/utils/oauthAffiliate'

const props = withDefaults(defineProps<{
  disabled?: boolean
  affCode?: string
  providerName?: string
  showDivider?: boolean
}>(), {
  providerName: 'OIDC',
  showDivider: true
})
const emit = defineEmits<{
  start: [request: OAuthLoginStart]
}>()

const route = useRoute()
const { t } = useI18n()

const normalizedProviderName = computed(() => {
  const name = props.providerName?.trim()
  return name || 'OIDC'
})

const providerInitial = computed(() => normalizedProviderName.value.charAt(0).toUpperCase() || 'O')

function startLogin(): void {
  const redirectTo = sanitizeInternalRedirect(route.query.redirect, '/dashboard')
  storeOAuthAffiliateCode(resolveAffiliateReferralCode(props.affCode, route.query.aff, route.query.aff_code))
  emit('start', { provider: 'oidc', params: { redirect: redirectTo } })
}
</script>

