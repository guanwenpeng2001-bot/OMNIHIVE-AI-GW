// Run from backend with go run ./api/v2/compose.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

type sections map[string]map[string]yaml.Node

type fragment struct {
	Paths      sections `yaml:"paths"`
	Components sections `yaml:"components"`
}

type document struct {
	OpenAPI  string            `yaml:"openapi"`
	Info     map[string]string `yaml:"info"`
	fragment `yaml:",inline"`
}

func main() {
	log.SetFlags(0)
	if err := compose(); err != nil {
		log.Fatal(err)
	}
}

func compose() error {
	files, err := filepath.Glob("api/v2/fragments/*.yaml")
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no OpenAPI fragments found under api/v2/fragments")
	}
	doc := document{
		OpenAPI:  "3.1.0",
		Info:     map[string]string{"title": "OmniHive API", "version": "2.0.0"},
		fragment: fragment{Paths: make(sections), Components: make(sections)},
	}
	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var source fragment
		decoder := yaml.NewDecoder(bytes.NewReader(data))
		decoder.KnownFields(true)
		if err := decoder.Decode(&source); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if err := merge(doc.Paths, source.Paths); err != nil {
			return fmt.Errorf("%s: paths: %w", path, err)
		}
		if err := merge(doc.Components, source.Components); err != nil {
			return fmt.Errorf("%s: components: %w", path, err)
		}
	}
	var output bytes.Buffer
	output.WriteString("# Generated by go run ./api/v2/compose. Edit the fragments instead.\n")
	encoder := yaml.NewEncoder(&output)
	encoder.SetIndent(2)
	if err := encoder.Encode(doc); err != nil {
		return err
	}
	if err := encoder.Close(); err != nil {
		return err
	}
	return os.WriteFile("api/v2/openapi.yaml", output.Bytes(), 0o644)
}

func merge(destination, source sections) error {
	for group, fields := range source {
		if destination[group] == nil {
			destination[group] = make(map[string]yaml.Node)
		}
		for field, value := range fields {
			if _, exists := destination[group][field]; exists {
				return fmt.Errorf("duplicate %q in %q", field, group)
			}
			destination[group][field] = value
		}
	}
	return nil
}
