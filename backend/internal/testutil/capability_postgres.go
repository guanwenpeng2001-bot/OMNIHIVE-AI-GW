// NewCapabilityPostgres supplies the existing capability handler fixture using
// only the exclusively assigned job_test database, never an application DB.
func NewCapabilityPostgres(t *testing.T) (*sql.DB, *dbent.Client, service.AccountRepository) {
	t.Helper()
	dsn := os.Getenv("UPSTREAM_JOB_TEST_DSN")
	if dsn == "" {
		t.Skip("set UPSTREAM_JOB_TEST_DSN to exclusive job_test")
	}
	db, err := sql.Open("postgres", dsn)
	require.NoError(t, err)
	t.Cleanup(func() { _ = db.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	var database string
	require.NoError(t, db.QueryRowContext(ctx, `SELECT current_database()`).Scan(&database))
	require.Equal(t, "job_test", database)
	require.NoError(t, repository.ApplyMigrations(ctx, db))
	client := dbent.NewClient(dbent.Driver(entsql.OpenDB(dialect.Postgres, db)))
	return db, client, repository.NewAccountRepository(client, db, nil)
}
